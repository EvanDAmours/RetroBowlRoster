"""Fetches current Madden ratings from EA's public ratings API and writes
nfl-rosters.js (the player data used by nfl-mod.js).

    python3 tools/nfl/fetch_rosters.py

Only the facts needed by the game are kept: name, position, overall, age,
speed and development trait.
"""
import json, os, time, urllib.request, urllib.parse

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "nfl-rosters.js")
API = "https://drop-api.ea.com/rating/madden-nfl"
POSITIONS = ["QB", "HB", "FB", "WR", "TE", "LT", "LG", "C", "RG", "RT", "DT", "LEDG", "REDG",
             "MIKE", "WILL", "SAM", "CB", "FS", "SS", "K", "P"]
# Retro Bowl uid (Teams.txt order) -> EA team id
EA_TEAM = [3, 12, 22, 18, 4, 9, 8, 23, 25, 2, 5, 29, 32, 10, 17, 30,
           11, 16, 13, 26, 7, 24, 15, 28, 1, 19, 20, 31, 14, 21, 27, 6]


def get(params):
    q = urllib.parse.urlencode(dict(dict(locale="en", limit=100), **params))
    for attempt in range(4):
        try:
            with urllib.request.urlopen(API + "?" + q, timeout=30) as r:
                if r.status == 204:
                    return {"items": [], "totalItems": 0}
                return json.load(r)
        except Exception:
            time.sleep(2 ** attempt)
    raise RuntimeError("request failed: " + q)


def get_all(params):
    out, offset = [], 0
    while True:
        d = get(dict(params, offset=offset))
        out += d["items"]
        offset += 100
        if offset >= d.get("totalItems", 0) or not d["items"]:
            return out


def dev(p):
    kinds = {(a.get("type") or {}).get("id") for a in p.get("playerAbilities") or []}
    return "X" if "xFactor" in kinds else "S" if "superstarAbility" in kinds else "N"


def main():
    pos_of = {}
    for pos in POSITIONS:
        for p in get_all(dict(position=pos)):
            pos_of[p["id"]] = pos
    teams = []
    for uid, ea in enumerate(EA_TEAM):
        players = []
        for p in get_all(dict(team=ea)):
            if p["id"] not in pos_of:
                continue
            stats = p.get("stats") or {}
            players.append(dict(
                fn=p["firstName"], ln=p["lastName"], pos=pos_of[p["id"]],
                ovr=p["overallRating"], age=p.get("age") or 25,
                spd=(stats.get("speed") or {}).get("value", 70), dev=dev(p)))
        players.sort(key=lambda x: -x["ovr"])
        teams.append(players)
        print(uid, ea, len(players), players[0]["fn"] + " " + players[0]["ln"] if players else "-")
    iteration = get(dict(limit=1))["items"][0]["iteration"]["label"]
    with open(OUT, "w") as f:
        f.write("// Generated by tools/nfl/fetch_rosters.py from Madden NFL ratings (" + iteration + ").\n")
        f.write("// Index == team uid in html5game/Teams.txt. Do not edit by hand.\n")
        f.write("window.NFL_ROSTERS = " + json.dumps(teams, separators=(",", ":")) + ";\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
